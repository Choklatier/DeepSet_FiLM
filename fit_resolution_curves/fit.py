def first_order_model(pt,a,b):
    return np.sqrt(a**2 + (b/pt)**2)

def fit(pt, res, tag = ""):
    popt, pcov = curve_fit(first_order_model,pt,res)

    pt_lin = np.linspace(pt[0],pt[-1],10000)
    plt.figure(figsize = (8,6))
    plt.xscale("log")
    plt.yscale("log")
    plt.scatter(pt,res,label = "measured resolution")
    plt.plot(pt_lin,first_order_model(pt_lin,*popt))
    plt.savefig(f"fit_{tag}.png")

    print("Fit results for ",tag)
    print("a = ",popt[0])
    print("b = ",popt[1])
    print("Covariance matrix = ",pcov)

